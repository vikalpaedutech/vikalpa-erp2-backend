import { Router } from "express";
import { verifyJWT } from "../../middlewares/auth.middlewares.js";
import { getHRMSMetadata, listHRRecords, createHRRecord, updateHRRecord, addHRRecordComment, archiveHRRecord } from "../../controllers/hr-management/hrms.controllers.js";
import { getAttendanceLeaveIntegration, createPayroll, listPayroll, updatePayrollStatus, downloadPayslip, getHRAnalytics } from "../../controllers/hr-management/hrms-advanced.controllers.js";
const router = Router();
router.use(verifyJWT);
router.get("/metadata", getHRMSMetadata);
router.get("/integration/attendance-leave", getAttendanceLeaveIntegration);
router.get("/analytics", getHRAnalytics);
router.get("/payroll", listPayroll);
router.post("/payroll/calculate", createPayroll);
router.patch("/payroll/:id/status", updatePayrollStatus);
router.get("/payroll/:id/payslip", downloadPayslip);
router.get("/records", listHRRecords);
router.post("/records", createHRRecord);
router.patch("/records/:id", updateHRRecord);
router.post("/records/:id/comments", addHRRecordComment);
router.delete("/records/:id", archiveHRRecord);
export default router;
